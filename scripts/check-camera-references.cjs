// Uses the installed browser runtime. No downloads, generated media, or scene writes.
const { join } = require('node:path');
const { homedir } = require('node:os');
let playwrightModule;
try { playwrightModule = require.resolve('playwright'); }
catch { playwrightModule = join(homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'); }
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || playwrightModule);
const { loadEnvConfig } = require('@next/env');
const { mkdirSync } = require('node:fs');
const assert = require('node:assert/strict');
loadEnvConfig(process.cwd());

(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const base = process.env.CAMERA_QA_URL || 'http://localhost:3000';
  const output = '.next/camera-reference-qa';
  mkdirSync(output, { recursive: true });
  await page.goto(`${base}/camera-references`);
  assert.match(page.url(), /\/login/);
  await page.getByLabel('Password', { exact: true }).fill(process.env.STORYBOARD_PASSWORD.trim());
  await page.getByRole('button', { name: 'Enter', exact: true }).click();
  await page.waitForURL(url => !url.pathname.includes('/login'), { timeout: 30000 });
  await page.goto(`${base}/camera-references`);
  await page.getByLabel('Section password').waitFor();
  assert.match(page.url(), /\/camera-references\/unlock/);
  assert.equal((await page.content()).includes('The camera physically translates through the scene'), false, 'Catalog is absent from the locked response');
  await page.getByLabel('Section password').fill('incorrect-test-password');
  await page.getByRole('button', { name: 'Unlock camera references' }).click();
  await page.getByRole('alert').waitFor();
  assert.match(page.url(), /\/unlock/);
  if (!process.env.CAMERA_QA_PASSWORD) throw new Error('Set CAMERA_QA_PASSWORD to test the section gate.');
  await page.getByLabel('Section password').fill(process.env.CAMERA_QA_PASSWORD);
  await page.getByRole('button', { name: 'Unlock camera references' }).click();
  await page.waitForURL(url => url.pathname === '/camera-references');
  await page.getByRole('heading', { name: 'Camera references.' }).waitFor();
  await page.getByRole('button', { name: 'Explore Dolly Shot', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: /^Explore / }).count(), 41);
  await page.screenshot({ path: `${output}/desktop.png`, fullPage: false });
  await page.getByRole('button', { name: 'Play study', exact: true }).click();
  const before = Number(await page.getByLabel('Study timeline').inputValue());
  await page.waitForTimeout(450);
  await page.getByRole('button', { name: 'Pause study', exact: true }).click();
  const after = Number(await page.getByLabel('Study timeline').inputValue());
  assert.notEqual(before, after, 'Playback advances time');
  await page.getByRole('button', { name: 'Restart study', exact: true }).click();
  assert.equal(await page.getByLabel('Study timeline').inputValue(), '0');
  await page.getByLabel('Search references').fill('crane');
  assert.equal(await page.getByRole('button', { name: /^Explore / }).count(), 1);
  await page.getByRole('button', { name: 'Explore Crane Shot', exact: true }).click();
  await page.getByRole('heading', { name: 'Crane Shot', exact: true }).first().waitFor();
  await page.getByRole('button', { name: 'Clear search' }).click();
  await page.getByRole('button', { name: 'List view' }).click();
  assert.equal(await page.getByRole('button', { name: /^Explore / }).count(), 41);
  await page.getByRole('button', { name: 'Grid view' }).click();
  await page.getByRole('button', { name: 'Save Crane Shot', exact: true }).first().click();
  await page.reload();
  await page.getByRole('button', { name: 'Unsave Crane Shot', exact: true }).first().waitFor();
  await page.getByRole('button', { name: /Saved references/ }).click();
  assert.equal(await page.getByRole('button', { name: /^Explore / }).count(), 1);
  await page.getByRole('button', { name: 'Unsave Crane Shot', exact: true }).first().click();
  await page.getByRole('heading', { name: 'Keep your go-to references here.' }).waitFor();
  await page.getByRole('button', { name: 'Browse all references' }).click();
  assert.equal(await page.getByRole('button', { name: /^Explore / }).count(), 150);
  await page.getByLabel('Search references').fill('not-a-real-technique');
  await page.getByRole('heading', { name: 'No references match these filters.' }).waitFor();
  await page.getByRole('button', { name: 'Clear search' }).click();
  await page.getByRole('button', { name: 'Compare view' }).click();
  assert.equal(await page.getByLabel('Comparison reference 1').count(), 1);
  assert.equal(await page.getByLabel('Comparison reference 2').count(), 1);
  await page.screenshot({ path: `${output}/compare.png`, fullPage: false });
  await page.getByRole('button', { name: 'Grid view' }).click();
  await page.getByRole('button', { name: 'Customize shot brief' }).click();
  await page.getByLabel('Story purpose').fill('Reveal the racetrack');
  assert.match(await page.getByLabel('Your shot brief').inputValue(), /Reveal the racetrack/);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('dialog[open]').count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${output}/mobile.png`, fullPage: false });
  await page.getByRole('button', { name: 'Saved references (0)' }).click();
  await page.getByRole('heading', { name: 'Keep your go-to references here.' }).waitFor();
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  assert.equal(overflow, false, 'No mobile horizontal overflow');
  await page.getByRole('button', { name: 'Lock section' }).click();
  await page.getByLabel('Section password').waitFor();
  await page.goto(`${base}/camera-references?shot=dolly-shot`);
  await page.getByLabel('Section password').waitFor();
  assert.match(page.url(), /\/unlock\?shot=dolly-shot/);
  assert.deepEqual(errors, [], 'No client runtime errors');
  console.log('PASS: main login, section gate, rejected wrong password, unlock/relock, protected deep links, 150-reference catalog, search, playback, reset, selection, list, saved persistence, empty states, comparison, shot brief, mobile width, and client runtime.');
  console.log(`Screenshots: ${output}`);
  await browser.close();
})().catch(error => { console.error(error.stack); process.exit(1); });
